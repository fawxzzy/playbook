import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { compareRuntimeSnapshots, formatReport, REGENERATE_COMMAND } from '../../scripts/check-cli-wrapper-runtime.mjs';

const makeGenerated = (files) => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'playbook-runtime-check-'));
  for (const [relative, content] of Object.entries(files)) {
    const target = path.join(dir, ...relative.split('/'));
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, content);
  }
  return dir;
};

const compare = (generated, committed) => {
  const dir = makeGenerated(generated);
  try {
    return compareRuntimeSnapshots({
      generatedDir: dir,
      committedFiles: Object.keys(committed),
      readCommitted: (relative) => committed[relative]
    });
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
};

test('a snapshot equal to the generated output passes with no report', () => {
  const files = { 'main.js': 'import "./lib/a.js";\n', 'lib/a.js': 'export const a = 1;\n' };
  const result = compare(files, files);

  assert.deepEqual(result, { stale: [], notCommitted: [], removed: [] });
  assert.equal(formatReport(result), null);
});

test('a CRLF-only difference does not fail', () => {
  const result = compare({ 'main.js': 'line one\nline two\n' }, { 'main.js': 'line one\r\nline two\r\n' });

  assert.deepEqual(result, { stale: [], notCommitted: [], removed: [] });
});

test('a changed generated file is reported as stale with an actionable message', () => {
  const result = compare({ 'commands/rules.js': 'new\n' }, { 'commands/rules.js': 'old\n' });

  assert.deepEqual(result.stale, ['commands/rules.js']);
  const report = formatReport(result);
  assert.match(report, /out of date with the current build/);
  assert.match(report, /commands\/rules\.js/);
  assert.match(report, /release\.requiredVersionBump\.missing/);
  assert.ok(report.includes(REGENERATE_COMMAND));
});

test('a generated file that is not committed is reported (committed files may import it)', () => {
  const result = compare(
    { 'commands/patterns.js': "import './patterns/verta.js';\n", 'commands/patterns/verta.js': 'export {};\n' },
    { 'commands/patterns.js': "import './patterns/verta.js';\n" }
  );

  assert.deepEqual(result.notCommitted, ['commands/patterns/verta.js']);
  assert.match(formatReport(result), /Generated by the build but not committed[\s\S]*commands\/patterns\/verta\.js/);
});

test('a committed file the build no longer generates is reported', () => {
  const result = compare({ 'main.js': 'x\n' }, { 'main.js': 'x\n', 'lib/old.js': 'y\n' });

  assert.deepEqual(result.removed, ['lib/old.js']);
  assert.match(formatReport(result), /Committed but no longer generated[\s\S]*lib\/old\.js/);
});

test('vendored node_modules are ignored on both sides', () => {
  const result = compare(
    { 'main.js': 'x\n', 'node_modules/pkg/index.js': 'generated\n' },
    { 'main.js': 'x\n', 'node_modules/other/index.js': 'committed\n' }
  );

  assert.deepEqual(result, { stale: [], notCommitted: [], removed: [] });
});
