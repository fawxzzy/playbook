#!/usr/bin/env node
// Guard: the committed packages/cli-wrapper/runtime snapshot must equal what
// scripts/prepare-cli-wrapper-runtime.mjs generates from the current build.
//
// Why: the test run regenerates this snapshot in place. A stale committed snapshot
// leaves a dirty tree in a shipping path, which makes `doctor` report
// release.requiredVersionBump.missing on every later run. This check finds the drift
// at PR time, with an actionable message, instead.
//
// Comparison is LF-normalized (Windows CRLF checkouts do not false-positive), skips
// vendored node_modules (git-ignored), and reads committed content from the git index.
import { execFileSync, spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const RUNTIME_RELATIVE_DIR = 'packages/cli-wrapper/runtime';
export const REGENERATE_COMMAND = [
  'pnpm -r build',
  'node scripts/prepare-cli-wrapper-runtime.mjs',
  `git add ${RUNTIME_RELATIVE_DIR}`
].join(' && ');

const normalize = (value) => value.replace(/\r\n/g, '\n');
const isVendored = (relativePath) => relativePath.split('/').includes('node_modules');

export const listFiles = (rootDir) => {
  const out = [];
  const walk = (dir) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        walk(full);
      } else {
        out.push(path.relative(rootDir, full).split(path.sep).join('/'));
      }
    }
  };
  if (fs.existsSync(rootDir)) walk(rootDir);
  return out.filter((file) => !isVendored(file)).sort();
};

/**
 * @param {{ generatedDir: string, committedFiles: string[], readCommitted: (relativePath: string) => string }} input
 * `committedFiles` are the runtime-relative paths tracked by git; `readCommitted` returns the committed text.
 * @returns {{ stale: string[], notCommitted: string[], removed: string[] }}
 */
export const compareRuntimeSnapshots = ({ generatedDir, committedFiles, readCommitted }) => {
  const generated = listFiles(generatedDir);
  const committed = new Set(committedFiles.filter((file) => !isVendored(file)));
  const stale = [];
  const notCommitted = [];

  for (const file of generated) {
    if (!committed.has(file)) {
      notCommitted.push(file);
      continue;
    }
    const generatedText = normalize(fs.readFileSync(path.join(generatedDir, ...file.split('/')), 'utf8'));
    if (generatedText !== normalize(readCommitted(file))) stale.push(file);
  }

  const generatedSet = new Set(generated);
  const removed = [...committed].filter((file) => !generatedSet.has(file)).sort();
  return { stale, notCommitted, removed };
};

export const formatReport = ({ stale, notCommitted, removed }) => {
  if (stale.length === 0 && notCommitted.length === 0 && removed.length === 0) return null;
  const lines = [`The committed ${RUNTIME_RELATIVE_DIR} snapshot is out of date with the current build.`];
  const section = (title, files) => {
    if (files.length === 0) return;
    lines.push('', `${title} (${files.length}):`, ...files.slice(0, 25).map((file) => `  - ${file}`));
    if (files.length > 25) lines.push(`  ... and ${files.length - 25} more`);
  };
  section('Changed by the build but not updated in the snapshot', stale);
  section('Generated by the build but not committed (committed files may import them)', notCommitted);
  section('Committed but no longer generated by the build', removed);
  lines.push(
    '',
    'Why this matters: the test run regenerates this snapshot, and a stale one makes `doctor` fail with',
    'release.requiredVersionBump.missing. A snapshot refresh is a shipping change, so also run',
    '`pnpm playbook release sync` (separate chore(release) commit) and add a CHANGELOG.md bullet.',
    '',
    `Fix: ${REGENERATE_COMMAND}`
  );
  return lines.join('\n');
};

const git = (repoRoot, args) => execFileSync('git', args, { cwd: repoRoot, encoding: 'utf8', maxBuffer: 256 * 1024 * 1024 });

const main = () => {
  const scriptDir = path.dirname(fileURLToPath(import.meta.url));
  const repoRoot = path.resolve(scriptDir, '..');
  const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'playbook-cli-wrapper-runtime-'));
  try {
    const generate = spawnSync(process.execPath, [path.join(scriptDir, 'prepare-cli-wrapper-runtime.mjs'), '--out', tmpDir], {
      cwd: repoRoot,
      encoding: 'utf8'
    });
    if (generate.status !== 0) {
      console.error(`Could not generate the cli-wrapper runtime (run "pnpm -r build" first).\n${(generate.stderr || generate.stdout || '').trim()}`);
      return 2;
    }

    const prefix = `${RUNTIME_RELATIVE_DIR}/`;
    const committedFiles = git(repoRoot, ['ls-files', '-z', '--', RUNTIME_RELATIVE_DIR])
      .split('\0')
      .filter(Boolean)
      .map((file) => file.slice(prefix.length));
    const result = compareRuntimeSnapshots({
      generatedDir: tmpDir,
      committedFiles,
      readCommitted: (relativePath) => git(repoRoot, ['show', `:${prefix}${relativePath}`])
    });

    const report = formatReport(result);
    if (report) {
      console.error(report);
      return 1;
    }
    console.log('cli-wrapper runtime snapshot matches the current build.');
    return 0;
  } finally {
    fs.rmSync(tmpDir, { recursive: true, force: true });
  }
};

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  process.exit(main());
}
